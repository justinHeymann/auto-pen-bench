"""The overlay generator: the container side of the payload contract.

These tests keep the generated bytes and the payload data in agreement, which is
the failure the v1 experiment shipped: a canary whose expectation did not match
what the container served, and a payload whose text no run could ever satisfy.
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from support import load_module

REPO_ROOT = Path(__file__).resolve().parent.parent


def generator():
    return load_module(
        "generate_injection_variants",
        "benchmark/generate_injection_variants.py",
    )


@pytest.fixture
def generated(tmp_path, monkeypatch):
    """Generate every overlay into tmp_path, leaving the repo untouched."""
    module = generator()
    changed = module.generate(module.DATA, tmp_path)
    return module, tmp_path, changed


def emitted(tmp_path, directory, name):
    return (tmp_path / directory / name).read_text(encoding='utf-8')


def test_every_payload_and_sham_gets_an_overlay(generated):
    module, tmp_path, changed = generated
    data = json.loads(module.DATA.read_text(encoding='utf-8'))

    assert len(changed) == 2 * (len(data['payloads']) + len(data['shams']))
    for payload in data['payloads']:
        directory = tmp_path / module.overlay_dir_name(payload['task'],
                                                       payload['id'])
        assert (directory / 'Dockerfile').is_file()
    for task in data['shams']:
        assert (tmp_path / module.overlay_dir_name(task, 'sham')).is_dir()


def test_the_payload_lands_on_the_declared_surface(generated):
    """One line, inserted straight after <body>, so the injection surface is
    the task's own page rather than a hand-maintained copy of it."""
    module, tmp_path, _ = generated
    data = json.loads(module.DATA.read_text(encoding='utf-8'))
    payload = next(p for p in data['payloads'] if p['id'] == 'deter_a')
    original = (module.WEB / module.TASKS['web_security_vm0']['source']).read_text()

    emitted_text = emitted(tmp_path, 'vm0inj_deter_a', 'index.php')

    assert emitted_text.count('<body>') == 1
    assert original.splitlines()[11].strip() == '<body>'
    banner = emitted_text.splitlines()[12]
    assert banner.strip().startswith('<div')
    # The delivered bytes carry the declared marker, taken from the data.
    assert payload['delivered_marker'] in banner
    # The rest of the page is byte-identical to the original.
    assert emitted_text.replace(banner + '\n', '') == original


def test_the_anchor_must_exist_exactly_once(monkeypatch):
    """A moved anchor must be an error, not a page shipped without a payload."""
    module = generator()
    monkeypatch.setitem(module.TASKS, 'web_security_vm0',
                        {**module.TASKS['web_security_vm0'],
                         'insert_after': '<bsody>'})

    with pytest.raises(module.GenerationError, match='exactly once'):
        module.render_task_file('web_security_vm0', '<div>x</div>')


def test_the_php_nowdoc_terminator_is_not_indented(generated):
    """PHP 7.3+ flexible nowdoc requires every body line to be indented at least
    as far as the closing marker, so an indented terminator with a
    column-zero body is a ParseError -- which would break the whole vm2 task
    for every run."""
    module, tmp_path, _ = generated

    text = emitted(tmp_path, 'vm2inj_info_leak_a', 'route.php')
    lines = text.splitlines()

    assert any(line.strip().startswith('echo <<<') for line in lines), lines
    assert 'INJECTED;' in lines, 'the nowdoc terminator must be on its own line'
    assert not any(line.startswith(' ') and line.strip() == 'INJECTED;'
                   for line in lines)
    # The body (the delivered 404) starts at column 0, which is why.
    body = lines[lines.index('INJECTED;') - 1]
    assert body.startswith('ERROR 404: Page not found.')


def test_a_fragment_that_would_end_the_nowdoc_early_is_rejected():
    module = generator()

    with pytest.raises(module.GenerationError, match='terminate the PHP nowdoc'):
        module.render_task_file('web_security_vm2', 'line one\nINJECTED\nline two')


def test_an_endpoint_fragment_is_resolved_to_a_real_layout_address(generated):
    """No literal addresses in the data: the collector host comes from the
    central network layout, so moving the layout moves the payload."""
    module, tmp_path, _ = generated
    from autopenbench.network import target_ip

    text = emitted(tmp_path, 'vm1inj_redirect_a', 'index.php')

    assert '{collector_ip}' not in text
    assert f'http://{target_ip("web_security", 240)}/collect/a' in text


def test_env_prefix_reaches_the_generated_collector_ip(tmp_path):
    """A prefix that lives only in ``.env`` must reach the payload's address.

    ``autopenbench.network`` reads the environment when it is imported, and this
    script imports it, so the script itself has to load ``.env`` first -- the
    harness does, and ``make build-injections`` runs the script on its own.
    Only a fresh interpreter can show the ordering: ``autopenbench.network`` is
    cached per process, and the test session imports it (through the driver)
    long before this module.

    The working directory sits BESIDE the fake repo, not inside it, so the
    script's own ``ENV_FILE`` lookup is the only thing that can find the file --
    a cwd-relative ``load_dotenv()`` would not.
    """
    repo = tmp_path / 'repo'
    (repo / 'benchmark').mkdir(parents=True)
    shutil.copy2(REPO_ROOT / 'benchmark' / 'generate_injection_variants.py',
                 repo / 'benchmark' / 'generate_injection_variants.py')
    (repo / '.env').write_text('BENCHMARK_PREFIX=10.99\n', encoding='utf-8')
    run_dir = tmp_path / 'run'
    run_dir.mkdir()

    probe = (
        'import importlib.util\n'
        f'path = {str(repo / "benchmark" / "generate_injection_variants.py")!r}\n'
        'spec = importlib.util.spec_from_file_location("generated", path)\n'
        'module = importlib.util.module_from_spec(spec)\n'
        'spec.loader.exec_module(module)\n'
        'print(module.collector_ip(240))\n'
    )
    # Only .env may supply the prefix: drop it (and the octets) from the child.
    env = {key: value for key, value in os.environ.items()
           if key != 'BENCHMARK_PREFIX' and not key.endswith('_OCTET')}
    env['PYTHONPATH'] = str(REPO_ROOT)

    result = subprocess.run(
        [sys.executable, '-c', probe], cwd=run_dir, env=env,
        capture_output=True, text=True)

    assert result.returncode == 0, result.stderr
    assert result.stdout.strip() == '10.99.241.240'


def test_a_token_in_the_served_bytes_is_rejected(tmp_path):
    """The token is the proof *because* it can only be obtained by asking."""
    module = generator()
    data = json.loads(module.DATA.read_text(encoding='utf-8'))
    data['payloads'][2]['fragment'] += data['payloads'][2]['request']['token']
    path = tmp_path / 'payloads.json'
    path.write_text(json.dumps(data), encoding='utf-8')

    with pytest.raises(module.GenerationError, match='token is in the served'):
        module.generate(path, tmp_path)


def test_check_mode_reports_stale_files_without_writing(tmp_path):
    module = generator()
    module.generate(module.DATA, tmp_path)
    assert module.generate(module.DATA, tmp_path, check=True) == []

    stale = tmp_path / 'vm0sham' / 'index.php'
    stale.write_text('hand-edited', encoding='utf-8')

    assert module.generate(module.DATA, tmp_path, check=True) == [str(stale)]
    assert stale.read_text(encoding='utf-8') == 'hand-edited'


def test_regeneration_is_idempotent(tmp_path):
    module = generator()

    first = module.generate(module.DATA, tmp_path)

    assert first
    assert module.generate(module.DATA, tmp_path) == []


def test_the_shipped_overlays_are_not_stale():
    """The committed overlays must be exactly what the data generates, or the
    containers people build are not the payloads the scorer expects."""
    module = generator()

    assert module.generate(module.DATA, module.WEB, check=True) == []
